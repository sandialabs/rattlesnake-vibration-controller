"""
Record the git commit SHA in the package at build time.

``rattlesnake.data`` reads the SHA to download the example data files that
match the exact commit a development build came from.

Attributes
----------
COMMIT_FILE : str
    Generated module, relative to the repository root.
"""

import pathlib
import subprocess
from typing import Any

from hatchling.builders.hooks.plugin.interface import BuildHookInterface

COMMIT_FILE = "src/rattlesnake/_commit.py"


def commit_read(*, root: str | pathlib.Path) -> str | None:
    """
    Return the SHA of the commit checked out in a git repository.

    Parameters
    ----------
    root : str or pathlib.Path
        Repository root.

    Returns
    -------
    str or None
        Full 40-character SHA of ``HEAD``. ``None`` when ``root`` holds no
        ``.git`` entry, as in an extracted sdist, or when git fails.
    """
    root = pathlib.Path(root)
    if not (root / ".git").exists():
        return None
    try:
        result = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=root,
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return result.stdout.strip()


class CommitBuildHook(BuildHookInterface):
    """
    Write ``COMMIT_FILE`` and include it in every build target.
    """

    PLUGIN_NAME = "custom"

    def initialize(self, version: str, build_data: dict[str, Any]) -> None:
        """
        Write the commit SHA before hatchling collects the package files.

        A build from an sdist has no git repository. It keeps the
        ``COMMIT_FILE`` that the sdist already holds.

        Parameters
        ----------
        version : str
            Build version, such as ``"standard"`` or ``"editable"``. Unused.
        build_data : dict
            Hatchling build data. The hook adds ``COMMIT_FILE`` to its
            ``artifacts`` list, because ``.gitignore`` lists the file.
        """
        path = pathlib.Path(self.root) / COMMIT_FILE
        commit = commit_read(root=self.root)
        if commit is not None or not path.exists():
            path.write_text(
                '"""Generated by hatch_build.py at build time. Do not edit."""\n'
                "\n"
                f"commit = {commit!r}\n",
                encoding="utf-8",
            )
        build_data["artifacts"].append(f"/{COMMIT_FILE}")

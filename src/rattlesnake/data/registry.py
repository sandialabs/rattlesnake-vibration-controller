"""
Generate ``_registry.py``, the SHA-256 registry of large example data files.

This module walks the examples directory and hashes every file whose suffix
``pyproject.toml`` excludes from the wheel and the sdist. It writes a
``registry`` dictionary that maps each name to its hash, sorted by name. Run it
from the repository root after any data file is added, removed, or changed::

    uv run python -m rattlesnake.data.registry
    uv run python -m rattlesnake.data.registry --check

The first command rewrites ``_registry.py`` and replaces its whole content. The
second command leaves the file alone. It prints the differences and exits with
status 1 when ``_registry.py`` is stale.

The generated text already follows ``ruff format``, so formatting the file
produces no diff. Each entry stays on one line because ruff cannot split a
string. The header disables pylint's ``line-too-long`` check for that reason, and
its module docstring satisfies pylint's ``missing-module-docstring`` check.

``pyproject.toml`` is the only list of registered suffixes. Hatchling reads
the ``exclude`` globs in ``[tool.hatch.build]`` to leave the files out of the
wheel and the sdist. ``suffixes_read`` reads the same globs, so every excluded
file is registered and none ships nowhere. ``pyproject.toml`` does not ship in
the wheel, so ``suffixes_read`` opens it only when called, never when this
module is imported.

Files that Rattlesnake writes do not belong in the registry. A
``SAVE_CONTROL_DATA`` profile event, for example, writes control data to a
path. Such a file changes on every run, so its hash never stays fixed, and
nothing reads it back. ``OUTPUT_FILES`` lists the output names that example
runs used to leave under the examples directory. ``file_list`` skips them
even when a stray copy exists on disk.

Attributes
----------
EXCLUDE_PREFIX : str
    Start of every ``exclude`` glob in ``pyproject.toml``. The suffix follows.
PYPROJECT_PATH : pathlib.Path
    The ``pyproject.toml`` at the root of a source checkout.
OUTPUT_FILES : frozenset of str
    Names, relative to the examples directory, of files that Rattlesnake
    writes. ``file_list`` skips them, so the registry never lists them.
HEADER : str
    Pylint directive and module docstring at the top of the generated file.
REGISTRY_PATH : pathlib.Path
    The ``_registry.py`` file that sits next to this module on disk.
"""

import argparse
import ast
import json
import os
import pathlib
import sys
import tomllib

from rattlesnake import data

EXCLUDE_PREFIX = "/src/rattlesnake/examples/**/*"
OUTPUT_FILES = frozenset(
    {
        "environment/random/random_control_data.nc4",
        "environment/sine/sine_control_data.npz",
    }
)
HEADER = (
    "# pylint: disable=line-too-long\n"
    '"""\n'
    "SHA-256 registry of the large example data files.\n"
    "\n"
    "Generated by: python -m rattlesnake.data.registry\n"
    "Do not edit by hand. Run the command above to regenerate this file.\n"
    "\n"
    "Each key is a file name relative to src/rattlesnake/examples/.\n"
    "Each value is the SHA-256 hash of that file.\n"
    "\n"
    "Files that Rattlesnake writes, such as SAVE_CONTROL_DATA outputs, do not\n"
    "belong here. See OUTPUT_FILES in rattlesnake/data/registry.py.\n"
    '"""\n'
    "\n"
)
REGISTRY_PATH = pathlib.Path(data.__file__).with_name("_registry.py")
PYPROJECT_PATH = pathlib.Path(__file__).resolve().parents[3] / "pyproject.toml"


def suffixes_read(*, path: str | os.PathLike[str] | None = None) -> tuple[str, ...]:
    """
    Read the registered file suffixes from the shared ``exclude`` globs.

    The globs live in ``[tool.hatch.build]``, where hatchling applies them to
    every build target. An ``exclude`` list on one target replaces the shared
    list for that target instead of adding to it, so the data files would ship
    in that archive. This function rejects such a list.

    Parameters
    ----------
    path : str or os.PathLike, optional
        A ``pyproject.toml`` file. Defaults to ``PYPROJECT_PATH``.

    Returns
    -------
    tuple of str
        Suffixes with the leading dot, sorted, such as ``(".nc4", ".npy")``.

    Raises
    ------
    FileNotFoundError
        If ``path`` does not exist, as in an installed wheel.
    ValueError
        If a build target sets its own ``exclude`` list, or if a glob does not
        have the form ``EXCLUDE_PREFIX`` followed by a suffix such as ``.nc4``.
    """
    if path is None:
        path = PYPROJECT_PATH
    with pathlib.Path(path).open("rb") as file:
        build_options = tomllib.load(file)["tool"]["hatch"]["build"]
    for target, options in build_options.get("targets", {}).items():
        if "exclude" in options:
            raise ValueError(
                f"{path}: [tool.hatch.build.targets.{target}] sets its own exclude "
                "list, which replaces [tool.hatch.build] exclude for that target"
            )
    suffixes = []
    for glob in sorted(build_options["exclude"]):
        suffix = glob.removeprefix(EXCLUDE_PREFIX)
        if (
            suffix == glob
            or len(suffix) < 2
            or not suffix.startswith(".")
            or any(character in suffix[1:] for character in "./*?[")
        ):
            raise ValueError(
                f"{path}: exclude glob {glob!r} is not {EXCLUDE_PREFIX!r} "
                "followed by a suffix such as '.nc4'"
            )
        suffixes.append(suffix)
    return tuple(suffixes)


def file_list(
    *,
    directory: str | os.PathLike[str],
    suffixes: tuple[str, ...] | None = None,
    excluded: frozenset[str] = OUTPUT_FILES,
) -> list[str]:
    """
    List the files under a directory that have one of the given suffixes.

    Parameters
    ----------
    directory : str or os.PathLike
        Directory to search, including all subdirectories.
    suffixes : tuple of str, optional
        File suffixes to keep, with the leading dot. Defaults to the suffixes
        that ``suffixes_read`` returns.
    excluded : frozenset of str, optional
        Relative names to skip. Defaults to ``OUTPUT_FILES``.

    Returns
    -------
    list of str
        Names relative to ``directory``, with ``/`` separators on every
        platform, sorted alphabetically.

    Raises
    ------
    FileNotFoundError
        If ``directory`` is not a directory, or if ``suffixes`` is ``None`` and
        ``PYPROJECT_PATH`` does not exist.
    ValueError
        If ``suffixes`` is ``None`` and ``suffixes_read`` rejects the
        ``exclude`` globs.
    """
    directory = pathlib.Path(directory)
    if not directory.is_dir():
        raise FileNotFoundError(f"not a directory: {directory}")
    if suffixes is None:
        suffixes = suffixes_read()
    names = (
        path.relative_to(directory).as_posix()
        for path in directory.rglob("*")
        if path.is_file() and path.suffix in suffixes
    )
    return sorted(name for name in names if name not in excluded)


def build(
    *,
    directory: str | os.PathLike[str] | None = None,
    suffixes: tuple[str, ...] | None = None,
) -> dict[str, str]:
    """
    Hash the data files under a directory.

    Parameters
    ----------
    directory : str or os.PathLike, optional
        Directory to search. Defaults to ``data.PACKAGE_DIRECTORY``.
    suffixes : tuple of str, optional
        File suffixes to register. Defaults to the suffixes that
        ``suffixes_read`` returns.

    Returns
    -------
    dict of str to str
        File name to SHA-256 hash, in sorted name order.
    """
    if directory is None:
        directory = data.PACKAGE_DIRECTORY
    directory = pathlib.Path(directory)
    return {
        name: data.hash_compute(path=directory / name)
        for name in file_list(directory=directory, suffixes=suffixes)
    }


def render(*, entries: dict[str, str]) -> str:
    """
    Format a registry as the source text of ``_registry.py``.

    Parameters
    ----------
    entries : dict of str to str
        File name to SHA-256 hash.

    Returns
    -------
    str
        ``HEADER`` followed by a ``registry`` dictionary with one line per
        entry. An empty registry is ``registry = {}``, which is how ruff
        formats it.
    """
    if not entries:
        return HEADER + "registry = {}\n"
    lines = [
        f"    {json.dumps(name)}: {json.dumps(digest)},\n"
        for name, digest in entries.items()
    ]
    return HEADER + "registry = {\n" + "".join(lines) + "}\n"


def generate(
    *,
    directory: str | os.PathLike[str] | None = None,
    suffixes: tuple[str, ...] | None = None,
) -> str:
    """
    Build the source text of ``_registry.py`` from the files on disk.

    Parameters
    ----------
    directory : str or os.PathLike, optional
        Directory to search. Defaults to ``data.PACKAGE_DIRECTORY``.
    suffixes : tuple of str, optional
        File suffixes to register. Defaults to the suffixes that
        ``suffixes_read`` returns.

    Returns
    -------
    str
        The text from ``render`` for the files that ``build`` finds.
    """
    return render(entries=build(directory=directory, suffixes=suffixes))


def read(*, path: str | os.PathLike[str]) -> dict[str, str]:
    """
    Read the ``registry`` dictionary from a generated file without running it.

    Parameters
    ----------
    path : str or os.PathLike
        Path of a file such as ``_registry.py``.

    Returns
    -------
    dict of str to str
        The literal value assigned to ``registry``.

    Raises
    ------
    ValueError
        If the file assigns no literal ``registry`` dictionary of strings.
    """
    tree = ast.parse(pathlib.Path(path).read_text(encoding="utf-8"))
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == "registry"
        ):
            value = ast.literal_eval(node.value)
            if isinstance(value, dict) and all(
                isinstance(key, str) and isinstance(item, str)
                for key, item in value.items()
            ):
                return value
    raise ValueError(f"{path} does not assign a registry dictionary of strings")


def difference_list(*, current: dict[str, str], generated: dict[str, str]) -> list[str]:
    """
    Describe how a registry differs from a freshly built one.

    Parameters
    ----------
    current : dict of str to str
        Registry in the existing ``_registry.py``.
    generated : dict of str to str
        Registry from ``build``.

    Returns
    -------
    list of str
        One line per difference, sorted by file name. A line starts with
        ``missing`` for a file on disk that the registry lacks, ``stale`` for a
        registry entry whose file is gone, or ``changed`` for a different hash.
        The list is empty when the registries match.
    """
    differences = []
    for name in sorted(current.keys() | generated.keys()):
        if name not in current:
            differences.append(f"missing  {name}")
        elif name not in generated:
            differences.append(f"stale    {name}")
        elif current[name] != generated[name]:
            differences.append(f"changed  {name}")
    return differences


def main(argv: list[str] | None = None) -> int:
    """
    Write ``_registry.py``, or check it with ``--check``.

    The command line accepts three options. ``--directory`` names the folder to
    search and defaults to the examples package. ``--output`` names the file to
    write or check and defaults to the ``_registry.py`` next to this module.
    ``--check`` compares instead of writing.

    Parameters
    ----------
    argv : list of str, optional
        Command-line arguments. Defaults to ``sys.argv[1:]``.

    Returns
    -------
    int
        0 after a write, or after a check that finds no differences. 1 after a
        check that finds differences. 2 if the search directory or
        ``pyproject.toml`` is missing, or if ``suffixes_read`` rejects the
        ``exclude`` globs.
    """
    parser = argparse.ArgumentParser(
        description="Generate _registry.py for the large example data files."
    )
    parser.add_argument("--directory", type=pathlib.Path, default=None)
    parser.add_argument("--output", type=pathlib.Path, default=REGISTRY_PATH)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    try:
        generated = build(directory=args.directory)
    except (FileNotFoundError, ValueError) as error:
        print(error, file=sys.stderr)
        return 2

    if not args.check:
        args.output.write_text(render(entries=generated), encoding="utf-8")
        print(f"Wrote {len(generated)} entries to {args.output}")
        return 0

    current = read(path=args.output) if args.output.exists() else {}
    differences = difference_list(current=current, generated=generated)
    for line in differences:
        print(line)
    if differences:
        print(f"{args.output} is stale. Run: python -m rattlesnake.data.registry")
        return 1
    print(f"{args.output} is up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
